/*
 * d3dx9_texture.c - D3DX9 texture creation: D3DXCreateTexture and the
 * D3DXCreateTextureFromFileInMemory family, D3DXGetImageInfoFromFileInMemory
 * and D3DXCheckTextureRequirements.
 *
 * Public contract per the D3DX9 documentation: loaders for BMP, TGA and DDS
 * (DXT1/3/5 plus the direct uncompressed formats of d3d9_format.h). All
 * pixels are filled through the real D3D9 calls (IDirect3DDevice9::
 * CreateTexture, IDirect3DTexture9::LockRect/UnlockRect), so nothing is
 * written directly into the HLE surface buffers and no guest pointer is
 * leaked. Anything we do not decode is an error, not a silent guess.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include "win32hle.h"
#include "d3d9_format.h"
#include "d3dx9_texture.h"

#ifndef D3DERR_INVALIDCALL
#define D3DERR_INVALIDCALL 0x8876086Cu
#endif
#ifndef D3DERR_OUTOFVIDEOMEMORY
#define D3DERR_OUTOFVIDEOMEMORY 0x8876017Cu
#endif
#ifndef D3DERR_NOTAVAILABLE
#define D3DERR_NOTAVAILABLE 0x8876086Au
#endif
#ifndef D3DXERR_INVALIDDATA
#define D3DXERR_INVALIDDATA 0x88760B59u  /* MAKE_DDHRESULT(2905), d3dx9.h */
#endif
#ifndef D3D_OK
#define D3D_OK 0u
#endif

/* ------------------------------------------------------------------ utils */

/* Unsupported input is reported on stderr with the real HRESULT, never with
 * a silent success. D3DX_FILTER_NONE / D3DX_FILTER_POINT (D3dx9tex.h) are the
 * only filters this loader implements: generated mips use nearest sampling. */
#define TEX_FILTER_NONE  1u
#define TEX_FILTER_POINT 2u

static void tex_log(const char *what) { fprintf(stderr, "[d3dx9] %s\n", what); }

static int image_filter_ok(uint32_t f, const char *which)
{
    if (f == TEX_FILTER_NONE || f == TEX_FILTER_POINT) return 1;
    fprintf(stderr, "[d3dx9] CreateTextureFromFileEx: %s=0x%08x not supported (only NONE/POINT)\n",
            which, f);
    return 0;
}

static uint16_t get16(const uint8_t *p) { return (uint16_t)(p[0] | ((uint16_t)p[1] << 8)); }
static uint32_t get32(const uint8_t *p) {
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}
static void put16(uint8_t *p, uint16_t v) { p[0]=(uint8_t)v; p[1]=(uint8_t)(v>>8); }
static void put32(uint8_t *p, uint32_t v) { p[0]=(uint8_t)v; p[1]=(uint8_t)(v>>8); p[2]=(uint8_t)(v>>16); p[3]=(uint8_t)(v>>24); }

static uint32_t full_chain(uint32_t w, uint32_t h)
{
    uint32_t m = w > h ? w : h;
    uint32_t n = 1;
    while (m > 1) { m >>= 1; n++; }
    return n;
}

static uint32_t level_dim(uint32_t v, uint32_t lvl)
{
    while (lvl > 0 && v > 1) { v >>= 1; lvl--; }
    return v;
}

/* ------------------------------------------------------------------ upload */

static int upload_level(uint32_t tex, uint32_t level, const uint8_t *src,
                        uint32_t w, uint32_t h, uint32_t fmt, uint32_t src_pitch);

/* Copy one level into the D3D9 texture through LockRect/UnlockRect. The data
 * is written row by row; the surface pitch comes back from the lock. */
static int upload_level(uint32_t tex, uint32_t level, const uint8_t *src,
                        uint32_t w, uint32_t h, uint32_t fmt, uint32_t src_pitch)
{
    void *lrp = hle_alloc(8);
    if (!lrp) return D3DERR_OUTOFVIDEOMEMORY;
    uint32_t lr_va = hle_va(lrp);
    uint32_t a[5] = { tex, level, lr_va, 0, 0 };
    uint32_t hr = hle_call_guest(hle_resolve("IDirect3DTexture9::LockRect"), 5, a);
    if (hr != D3D_OK) { hle_free(lrp); return hr; }
    D3DLOCKED_RECT lr;
    memcpy(&lr, lrp, 8);
    uint8_t *dst = hle_ptr(lr.pBits);
    uint32_t dst_pitch = lr.Pitch > 0 ? (uint32_t)lr.Pitch : 0;
    uint32_t bpp = d3d9_format_bytes_per_pixel(fmt);
    if (bpp) {
        for (uint32_t y = 0; y < h; y++)
            memcpy(dst + (size_t)y * dst_pitch, src + (size_t)y * src_pitch, (size_t)w * bpp);
    } else {
        uint32_t bb = d3d9_format_block_bytes(fmt);
        if (!bb) { hle_free(lrp); return D3DERR_NOTAVAILABLE; }
        uint32_t bw = (w + 3) / 4, bh = (h + 3) / 4;
        for (uint32_t y = 0; y < bh; y++)
            memcpy(dst + (size_t)y * dst_pitch, src + (size_t)y * bw * bb, (size_t)bw * bb);
    }
    hle_free(lrp);
    uint32_t b[2] = { tex, level };
    hle_call_guest(hle_resolve("IDirect3DTexture9::UnlockRect"), 2, b);
    return 0;
}

/* Upload the decoded A8R8G8B8 base of a TGA/BMP file. Levels above 0 are
 * generated by 2x downsampling of the base (nearest). */
static int upload_levels_decoded(uint32_t tex, const uint8_t *base,
                                 uint32_t w0, uint32_t h0, uint32_t levels)
{
    int hr = upload_level(tex, 0, base, w0, h0, D3DFMT_A8R8G8B8, w0 * 4);
    if (hr) return hr;
    for (uint32_t i = 1; i < levels; i++) {
        uint32_t w = level_dim(w0, i), h = level_dim(h0, i);
        uint8_t *mip = (uint8_t *)malloc((size_t)w * h * 4);
        if (!mip) return D3DERR_OUTOFVIDEOMEMORY;
        for (uint32_t y = 0; y < h; y++) {
            uint32_t sy = (y << i) < h0 ? (y << i) : h0 - 1;
            for (uint32_t x = 0; x < w; x++) {
                uint32_t sx = (x << i) < w0 ? (x << i) : w0 - 1;
                memcpy(mip + ((size_t)y * w + x) * 4, base + ((size_t)sy * w0 + sx) * 4, 4);
            }
        }
        hr = upload_level(tex, i, mip, w, h, D3DFMT_A8R8G8B8, w * 4);
        free(mip);
        if (hr) return hr;
    }
    return 0;
}

/* All image decoders allocate a sibling-sized RGBA buffer. Reject dimensions
 * that would overflow 32-bit arithmetic or exceed the D3D9 texture limits
 * before any multiplication or allocation. */
static int tex_alloc_ok(uint32_t w, uint32_t h) {
    if (w == 0 || h == 0 || w > D3D9_TEX_MAX_DIM || h > D3D9_TEX_MAX_DIM) return 0;
    return (uint64_t)w * (uint64_t)h * 4u <= D3D9_TEX_MAX_SRC;
}

/* ------------------------------------------------------------- DDS decode */

static int dds_info(const uint8_t *d, uint32_t size, d3dx9_texture_info *info)
{
    if (size < 128) return D3DERR_INVALIDCALL;
    if (d[0] != 'D' || d[1] != 'D' || d[2] != 'S' || d[3] != ' ')
        return D3DERR_INVALIDCALL;
    const uint8_t *h = d + 4;
    if (get32(h + 0) < 124) return D3DERR_INVALIDCALL;
    uint32_t caps2 = get32(h + 108);
    if (get32(h + 20) > 1) return D3DERR_NOTAVAILABLE;        /* volume texture */
    int is_cube = (caps2 & 0x200u) != 0;                      /* DDSCAPS2_CUBEMAP */
    const uint8_t *pf = h + 72;
    if (get32(pf + 0) < 32) return D3DERR_INVALIDCALL;
    uint32_t pfFlags = get32(pf + 4), fourcc = get32(pf + 8), bits = get32(pf + 12);
    uint32_t r = get32(pf + 16), g = get32(pf + 20), b = get32(pf + 24), a = get32(pf + 28);

    uint32_t fmt = 0;
    if (pfFlags & 0x00000004) {                              /* DDPF_FOURCC */
        switch (fourcc) {
        case D3DFMT_DXT1: fmt = D3DFMT_DXT1; break;
        case D3DFMT_DXT3: fmt = D3DFMT_DXT3; break;
        case D3DFMT_DXT5: fmt = D3DFMT_DXT5; break;
        default: return D3DERR_NOTAVAILABLE;                 /* DXT2/4, YUV, ... */
        }
    } else if (pfFlags & 0x00000040) {                       /* DDPF_RGB */
        if (bits == 32) {
            if (r == 0x00FF0000 && g == 0x0000FF00 && b == 0x000000FF && a == 0xFF000000)
                fmt = D3DFMT_A8R8G8B8;
            else if (r == 0x00FF0000 && g == 0x0000FF00 && b == 0x000000FF)
                fmt = D3DFMT_X8R8G8B8;
            else return D3DERR_NOTAVAILABLE;
        } else if (bits == 16) {
            if (r == 0xF800 && g == 0x07E0 && b == 0x001F)
                fmt = D3DFMT_R5G6B5;
            else if (r == 0x7C00 && g == 0x03E0 && b == 0x001F && a == 0x8000)
                fmt = D3DFMT_A1R5G5B5;
            else if (r == 0x7C00 && g == 0x03E0 && b == 0x001F)
                fmt = D3DFMT_X1R5G5B5;
            else if (r == 0x0F00 && g == 0x00F0 && b == 0x000F && a == 0xF000)
                fmt = D3DFMT_A4R4G4B4;
            else if (r == 0x0F00 && g == 0x00F0 && b == 0x000F)
                fmt = D3DFMT_X4R4G4B4;
            else return D3DERR_NOTAVAILABLE;
        } else return D3DERR_NOTAVAILABLE;
    } else if (pfFlags & 0x00020000) {                       /* DDPF_LUMINANCE */
        if (bits == 8)
            fmt = (pfFlags & 0x1) ? D3DFMT_A8L8 : D3DFMT_L8; /* ALPHAPIXELS -> A8L8 */
        else return D3DERR_NOTAVAILABLE;
    } else if (pfFlags & 0x00000002) {                       /* DDPF_ALPHA */
        fmt = D3DFMT_A8;
    } else return D3DERR_NOTAVAILABLE;
    if (!d3d9_format_is_supported(fmt)) return D3DERR_NOTAVAILABLE;

    uint32_t w = get32(h + 12), ht = get32(h + 8);
    if (w == 0 || ht == 0) return D3DERR_INVALIDCALL;
    uint32_t mips = get32(h + 24);
    if (is_cube) {
        uint32_t faces = caps2 & 0xFC00u;
        /* require all 6 cube faces */
        if (faces != 0xFC00u) return D3DERR_NOTAVAILABLE;
    }
    if (!tex_alloc_ok(w, ht)) return D3DERR_INVALIDCALL;
    info->Width = w;
    info->Height = ht;
    info->Depth = 0;
    info->MipLevels = mips ? mips : 1;
    info->Format = fmt;
    info->ResourceType = is_cube ? D3DRTYPE_CUBETEXTURE : D3DRTYPE_TEXTURE;
    info->ImageFileFormat = D3DXIFF_DDS;
    return 0;
}

static int dds_upload(uint32_t tex, const uint8_t *d, uint32_t size,
                      const d3dx9_texture_info *info, uint32_t levels)
{
    uint32_t off = 128;
    for (uint32_t i = 0; i < levels; i++) {
        uint32_t w = level_dim(info->Width, i), h = level_dim(info->Height, i);
        uint32_t sz = d3d9_format_level_size(info->Format, w, h);
        if (!sz || off + sz > size) return D3DERR_INVALIDCALL;
        int hr = upload_level(tex, i, d + off, w, h, info->Format,
                              d3d9_format_pitch(info->Format, w));
        if (hr) return hr;
        off += sz;
    }
    return 0;
}

static int upload_cube_level(uint32_t tex, uint32_t face, uint32_t level,
                             const void *data, uint32_t w, uint32_t h,
                             uint32_t fmt, uint32_t src_pitch)
{
    void *lr_mem = hle_alloc(sizeof(D3DLOCKED_RECT));
    if (!lr_mem) return D3DERR_OUTOFVIDEOMEMORY;
    uint32_t lr_va = hle_va(lr_mem);
    /* IDirect3DCubeTexture9::LockRect(this, FaceType, Level, pLockedRect, pRect, Flags) */
    uint32_t a[6] = { tex, face, level, lr_va, 0, 0 };
    uint32_t hr = hle_call_guest(hle_resolve("IDirect3DCubeTexture9::LockRect"), 6, a);
    if (hr) { hle_free(lr_mem); return (int)hr; }
    D3DLOCKED_RECT lr; memcpy(&lr, lr_mem, sizeof(lr));
    hle_free(lr_mem);
    uint8_t *dst = (uint8_t *)hle_ptr(lr.pBits);
    if (d3d9_format_is_block_compressed(fmt)) {
        uint32_t sh = (h + 3) / 4;
        for (uint32_t row = 0; row < sh; row++)
            memcpy(dst + (size_t)row * (uint32_t)lr.Pitch,
                   (const uint8_t *)data + (size_t)row * src_pitch, src_pitch);
    } else {
        uint32_t bpp = d3d9_format_bytes_per_pixel(fmt);
        for (uint32_t y = 0; y < h; y++)
            memcpy(dst + (size_t)y * (uint32_t)lr.Pitch,
                   (const uint8_t *)data + (size_t)y * src_pitch, (size_t)w * bpp);
    }
    uint32_t ua[3] = { tex, face, level };
    hle_call_guest(hle_resolve("IDirect3DCubeTexture9::UnlockRect"), 3, ua);
    return 0;
}

static int dds_upload_cube(uint32_t tex, const uint8_t *d, uint32_t size,
                           const d3dx9_texture_info *info, uint32_t levels)
{
    uint32_t off = 128;
    for (uint32_t face = 0; face < 6; face++) {
        for (uint32_t i = 0; i < levels; i++) {
            uint32_t w = level_dim(info->Width, i), h = level_dim(info->Height, i);
            uint32_t sz = d3d9_format_level_size(info->Format, w, h);
            if (!sz || off + sz > size) return D3DERR_INVALIDCALL;
            int hr = upload_cube_level(tex, face, i, d + off, w, h, info->Format,
                                       d3d9_format_pitch(info->Format, w));
            if (hr) return hr;
            off += sz;
        }
    }
    return 0;
}

/* -------------------------------------------------------------- TGA decode */

static int tga_info(const uint8_t *d, uint32_t size, d3dx9_texture_info *info)
{
    if (size < 18) return D3DERR_INVALIDCALL;
    uint32_t idLen = d[0], cmapType = d[1], imgType = d[2];
    uint32_t width = get16(d + 12), height = get16(d + 14);
    uint32_t bpp = d[16];
    if (cmapType != 0) return D3DERR_NOTAVAILABLE;           /* palettized TGA */
    if (imgType != 2 && imgType != 3) return D3DERR_INVALIDCALL;
    if (width == 0 || height == 0 || !tex_alloc_ok(width, height)) return D3DERR_INVALIDCALL;
    if (imgType == 2 && bpp != 16 && bpp != 24 && bpp != 32)
        return D3DERR_NOTAVAILABLE;
    if (imgType == 3 && bpp != 8)
        return D3DERR_NOTAVAILABLE;
    uint64_t rowBytes = (uint64_t)(bpp / 8) * width;
    if ((uint64_t)18 + idLen + (uint64_t)height * rowBytes > size)
        return D3DERR_INVALIDCALL;
    info->Width = width;
    info->Height = height;
    info->Depth = 1;
    info->MipLevels = 1;
    info->Format = D3DFMT_A8R8G8B8;
    info->ResourceType = D3DRTYPE_TEXTURE;
    info->ImageFileFormat = D3DXIFF_TGA;
    return 0;
}

static int tga_decode(const uint8_t *d, uint32_t size, d3dx9_texture_info *info, uint8_t **out)
{
    int hr = tga_info(d, size, info);
    if (hr) return hr;
    uint32_t w = info->Width, h = info->Height, bpp = d[16];
    uint8_t *base = (uint8_t *)malloc((size_t)w * h * 4);
    if (!base) return D3DERR_OUTOFVIDEOMEMORY;
    const uint8_t *px = d + 18 + d[0];
    uint64_t rowBytes = (uint64_t)(bpp / 8) * w;
    int topDown = (d[17] & 0x20) != 0;                       /* bit 5: origin top */
    for (uint32_t y = 0; y < h; y++) {
        uint32_t sy = topDown ? y : (h - 1 - y);
        const uint8_t *row = px + (size_t)sy * rowBytes;
        for (uint32_t x = 0; x < w; x++) {
            const uint8_t *q = row + (size_t)x * (bpp / 8);
            uint32_t r = 0, g = 0, b = 0, a = 255;
            switch (bpp) {
            case 24: b = q[0]; g = q[1]; r = q[2]; break;
            case 32: b = q[0]; g = q[1]; r = q[2]; a = q[3]; break;
            case 16: {
                uint16_t v = (uint16_t)(q[0] | ((uint16_t)q[1] << 8));
                r = (v >> 10) & 0x1F; g = (v >> 5) & 0x1F; b = v & 0x1F;
                a = (v & 0x8000) ? 0xFF : 0;                 /* A1R5G5B5 */
                break;
            }
            default: b = g = r = q[0]; break;                /* 8 bpp gray */
            }
            ((uint32_t *)base)[(size_t)y * w + x] = (a << 24) | (r << 16) | (g << 8) | b;
        }
    }
    *out = base;
    return 0;
}

/* --------------------------------------------------------------- BMP decode */

static int bmp_info(const uint8_t *d, uint32_t size, d3dx9_texture_info *info)
{
    if (size < 54) return D3DERR_INVALIDCALL;
    if (d[0] != 'B' || d[1] != 'M') return D3DERR_INVALIDCALL;
    uint32_t dibSize = get32(d + 14);
    if (dibSize < 40) return D3DERR_NOTAVAILABLE;            /* not a classic BMP */
    uint32_t bfOff = get32(d + 10);
    int32_t w = (int32_t)get32(d + 18);
    int32_t h = (int32_t)get32(d + 22);
    uint32_t bpp = get16(d + 28);
    uint32_t compression = get32(d + 30);
    if (w <= 0 || h == 0) return D3DERR_INVALIDCALL;
    if (compression != 0) return D3DERR_NOTAVAILABLE;        /* BI_RGB only */
    if (bpp != 24 && bpp != 32 && bpp != 16) return D3DERR_NOTAVAILABLE;
    int topDown = h < 0;
    uint32_t hh = topDown ? (uint32_t)(-h) : (uint32_t)h;
    if (!tex_alloc_ok((uint32_t)w, hh)) return D3DERR_INVALIDCALL;
    info->Width = (uint32_t)w;
    info->Height = hh;
    info->Depth = 1;
    info->MipLevels = 1;
    info->Format = D3DFMT_A8R8G8B8;
    info->ResourceType = D3DRTYPE_TEXTURE;
    info->ImageFileFormat = D3DXIFF_BMP;
    (void)bfOff;                                             /* validated in bmp_decode */
    return 0;
}

static int bmp_decode(const uint8_t *d, uint32_t size, d3dx9_texture_info *info, uint8_t **out)
{
    int hr = bmp_info(d, size, info);
    if (hr) return hr;
    uint32_t w = info->Width, h = info->Height, bpp = get16(d + 28);
    uint32_t bfOff = get32(d + 10);
    int topDown = (int32_t)get32(d + 22) < 0;
    uint64_t rowBytes = (((uint64_t)w * bpp + 31u) / 32u) * 4u;  /* rows 4-byte aligned */
    if ((uint64_t)bfOff + rowBytes * h > size) return D3DERR_INVALIDCALL;
    uint8_t *base = (uint8_t *)malloc((size_t)w * h * 4);
    if (!base) return D3DERR_OUTOFVIDEOMEMORY;
    for (uint32_t y = 0; y < h; y++) {
        uint32_t sy = topDown ? y : (h - 1 - y);
        const uint8_t *row = d + bfOff + (size_t)sy * rowBytes;
        for (uint32_t x = 0; x < w; x++) {
            const uint8_t *q = row + (size_t)x * bpp / 8;
            uint32_t r = 0, g = 0, b = 0, a = 255;
            switch (bpp) {
            case 24: b = q[0]; g = q[1]; r = q[2]; break;
            case 32: b = q[0]; g = q[1]; r = q[2]; a = q[3]; break;
            default: {                                       /* 16 bpp, 555 */
                uint16_t v = get16(q);
                r = (v >> 10) & 0x1F; g = (v >> 5) & 0x1F; b = v & 0x1F; a = 255;
                break;
            }
            }
            ((uint32_t *)base)[(size_t)y * w + x] = (a << 24) | (r << 16) | (g << 8) | b;
        }
    }
    *out = base;
    return 0;
}

/* ------------------------------------------------------------------ sniffing */

static int sniff(const uint8_t *d, uint32_t size, uint32_t *which)
{
    if (size >= 2 && d[0] == 'B' && d[1] == 'M') { *which = D3DXIFF_BMP; return 0; }
    if (size >= 4 && d[0] == 'D' && d[1] == 'D' && d[2] == 'S' && d[3] == ' ')
        { *which = D3DXIFF_DDS; return 0; }
    if (size >= 18) { *which = D3DXIFF_TGA; return 0; }
    return D3DERR_INVALIDCALL;
}

/* ------------------------------------------------------------------ create */

int d3dx9_texture_create(uint32_t dev, uint32_t w, uint32_t h, uint32_t levels,
                         uint32_t usage, uint32_t fmt, uint32_t pool, uint32_t *ppTex)
{
    if (!dev || !ppTex) return D3DERR_INVALIDCALL;
    if (!w || !h || w > D3D9_TEX_MAX_DIM || h > D3D9_TEX_MAX_DIM)
        return D3DERR_INVALIDCALL;
    if (!d3d9_format_is_supported(fmt)) return D3DERR_NOTAVAILABLE;
    if (usage & ~(D3DUSAGE_RENDERTARGET | D3DUSAGE_DYNAMIC | D3DUSAGE_AUTOGENMIPMAP))
        return D3DERR_INVALIDCALL;
    if (pool > D3DPOOL_SYSTEMMEM) return D3DERR_INVALIDCALL;

    uint32_t chain = full_chain(w, h);
    if (levels == 0 || levels == D3DX_DEFAULT) {
        levels = chain;
    } else {
        if (levels > D3D9_TEX_MAX_LEVELS) return D3DERR_INVALIDCALL;
        if (levels > chain) levels = chain;
        if (!levels) levels = 1;
    }

    *ppTex = 0;
    void *outp = hle_alloc(4);
    if (!outp) return D3DERR_OUTOFVIDEOMEMORY;
    uint32_t out_va = hle_va(outp);
    uint32_t a[9] = { dev, w, h, levels, usage, fmt, pool, out_va, 0 };
    uint32_t hr = hle_call_guest(hle_resolve("IDirect3DDevice9::CreateTexture"), 9, a);
    if (!hr) *ppTex = MEM32(out_va);
    hle_free(outp);
    return hr;
}

int d3dx9_texture_decode_top_level(const void *pSrcData, uint32_t size,
                                   d3dx9_texture_info *pSrcInfo,
                                   const uint8_t **top_data, uint32_t *top_pitch,
                                   uint32_t *top_fmt, uint8_t **decoded_rgba)
{
    if (decoded_rgba) *decoded_rgba = NULL;
    if (top_data) *top_data = NULL;
    if (top_pitch) *top_pitch = 0;
    if (top_fmt) *top_fmt = 0;
    if (!pSrcData || !pSrcInfo || !top_data || !top_pitch || !top_fmt || !decoded_rgba || !size)
        return D3DERR_INVALIDCALL;
    uint32_t which;
    int hr = sniff(pSrcData, size, &which);
    if (hr) return hr;
    memset(pSrcInfo, 0, sizeof *pSrcInfo);
    if (which == D3DXIFF_DDS) {
        hr = dds_info(pSrcData, size, pSrcInfo);
        if (hr) return hr;
        uint32_t sz = d3d9_format_level_size(pSrcInfo->Format, pSrcInfo->Width, pSrcInfo->Height);
        if (!sz || 128u + sz > size) return D3DERR_INVALIDCALL;
        *top_data = (const uint8_t *)pSrcData + 128;
        *top_pitch = d3d9_format_pitch(pSrcInfo->Format, pSrcInfo->Width);
        *top_fmt = pSrcInfo->Format;
        *decoded_rgba = NULL;
        return 0;
    }
    uint8_t *base = NULL;
    hr = (which == D3DXIFF_TGA) ? tga_decode(pSrcData, size, pSrcInfo, &base)
        : bmp_decode(pSrcData, size, pSrcInfo, &base);
    if (hr) return hr;
    *top_data = base;
    *top_pitch = pSrcInfo->Width * 4u;
    *top_fmt = D3DFMT_A8R8G8B8;
    *decoded_rgba = base;
    return 0;
}

int d3dx9_texture_get_image_info(const void *pSrcData, uint32_t size, d3dx9_texture_info *pSrcInfo)
{
    if (!pSrcData || !pSrcInfo || !size) return D3DERR_INVALIDCALL;
    uint32_t which;
    int hr = sniff(pSrcData, size, &which);
    if (hr) return hr;
    memset(pSrcInfo, 0, sizeof *pSrcInfo);
    hr = (which == D3DXIFF_DDS) ? dds_info(pSrcData, size, pSrcInfo)
        : (which == D3DXIFF_TGA) ? tga_info(pSrcData, size, pSrcInfo)
        : bmp_info(pSrcData, size, pSrcInfo);
    return hr;
}

int d3dx9_texture_check_requirements(uint32_t dev, uint32_t *pWidth, uint32_t *pHeight,
                                     uint32_t *pNumMipLevels, uint32_t Usage,
                                     uint32_t *pFormat, uint32_t Pool)
{
    if (!dev) return D3DERR_INVALIDCALL;
    uint32_t w = pWidth ? *pWidth : 0, h = pHeight ? *pHeight : 0;
    if (w == 0 && h != 0) w = h;
    if (h == 0 && w != 0) h = w;
    if (w == 0) w = 256;
    if (h == 0) h = 256;
    if (w > D3D9_TEX_MAX_DIM) w = D3D9_TEX_MAX_DIM;
    if (h > D3D9_TEX_MAX_DIM) h = D3D9_TEX_MAX_DIM;
    if (pWidth) *pWidth = w;
    if (pHeight) *pHeight = h;
    if (pNumMipLevels && (*pNumMipLevels == 0 || *pNumMipLevels == D3DX_DEFAULT))
        *pNumMipLevels = full_chain(w, h);
    if (pFormat && *pFormat == D3DFMT_UNKNOWN) *pFormat = D3DFMT_A8R8G8B8;
    if (pNumMipLevels && *pNumMipLevels > D3D9_TEX_MAX_LEVELS)
        *pNumMipLevels = D3D9_TEX_MAX_LEVELS;
    if (Usage & ~(D3DUSAGE_RENDERTARGET | D3DUSAGE_DYNAMIC | D3DUSAGE_AUTOGENMIPMAP))
        return D3DERR_INVALIDCALL;
    if (Pool > D3DPOOL_SYSTEMMEM) return D3DERR_INVALIDCALL;
    return 0;
}

static int read_file_all(const char *path, uint8_t **out, uint32_t *out_size)
{
    if (!path || !out || !out_size) return D3DERR_INVALIDCALL;
    *out = NULL;
    *out_size = 0;
    FILE *f = fopen(path, "rb");
    if (!f) { fprintf(stderr, "[d3dx9] cannot open image file '%s'\n", path); return D3DXERR_INVALIDDATA; }
    if (fseek(f, 0, SEEK_END) != 0) {
        fclose(f); tex_log("cannot seek image file"); return D3DXERR_INVALIDDATA;
    }
    long sz = ftell(f);
    if (sz <= 0 || sz > (long)D3D9_TEX_MAX_SRC) {
        fclose(f); fprintf(stderr, "[d3dx9] image file '%s' has invalid size %ld\n", path, sz);
        return D3DERR_INVALIDCALL;
    }
    if (fseek(f, 0, SEEK_SET) != 0) {
        fclose(f); tex_log("cannot rewind image file"); return D3DXERR_INVALIDDATA;
    }
    uint8_t *data = (uint8_t *)malloc((size_t)sz);
    if (!data) { fclose(f); tex_log("out of memory reading image file"); return D3DERR_OUTOFVIDEOMEMORY; }
    if (fread(data, 1, (size_t)sz, f) != (size_t)sz) {
        free(data); fclose(f); tex_log("short read from image file");
        return D3DERR_INVALIDCALL;
    }
    fclose(f);
    *out = data;
    *out_size = (uint32_t)sz;
    return 0;
}

static size_t d3dx9_utf16_to_utf8(const uint16_t *src, char *dst, size_t cap)
{
    size_t n = 0;
    if (!dst || cap == 0) return 0;
    if (!src) { dst[0] = 0; return 0; }
    while (*src) {
        uint32_t cp = *src++;
        if (cp >= 0xD800 && cp <= 0xDBFF && *src >= 0xDC00 && *src <= 0xDFFF) {
            cp = 0x10000u + ((cp - 0xD800u) << 10) + (*src++ - 0xDC00u);
        }
        size_t need = (cp < 0x80) ? 1 : (cp < 0x800) ? 2 : (cp < 0x10000) ? 3 : 4;
        if (n + need >= cap) break;
        if (need == 1) dst[n++] = (char)cp;
        else if (need == 2) { dst[n++] = (char)(0xC0 | (cp >> 6)); dst[n++] = (char)(0x80 | (cp & 0x3F)); }
        else if (need == 3) { dst[n++] = (char)(0xE0 | (cp >> 12)); dst[n++] = (char)(0x80 | ((cp >> 6) & 0x3F)); dst[n++] = (char)(0x80 | (cp & 0x3F)); }
        else { dst[n++] = (char)(0xF0 | (cp >> 18)); dst[n++] = (char)(0x80 | ((cp >> 12) & 0x3F)); dst[n++] = (char)(0x80 | ((cp >> 6) & 0x3F)); dst[n++] = (char)(0x80 | (cp & 0x3F)); }
    }
    dst[n] = 0;
    return n;
}

