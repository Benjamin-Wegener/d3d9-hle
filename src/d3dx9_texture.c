static int fill_write_pixel(uint8_t *dst, uint32_t fmt, const float rgba[4])
{
    float r = rgba[0], g = rgba[1], b = rgba[2], a = rgba[3];
    if (r < 0) r = 0; if (r > 1) r = 1;
    if (g < 0) g = 0; if (g > 1) g = 1;
    if (b < 0) b = 0; if (b > 1) b = 1;
    if (a < 0) a = 0; if (a > 1) a = 1;
    uint32_t R = (uint32_t)(r * 255.0f + 0.5f);
    uint32_t G = (uint32_t)(g * 255.0f + 0.5f);
    uint32_t B = (uint32_t)(b * 255.0f + 0.5f);
    uint32_t A = (uint32_t)(a * 255.0f + 0.5f);
    switch (fmt) {
    case D3DFMT_A8R8G8B8: case D3DFMT_X8R8G8B8:
        dst[0]=(uint8_t)B; dst[1]=(uint8_t)G; dst[2]=(uint8_t)R; dst[3]=(uint8_t)(fmt==D3DFMT_X8R8G8B8?255:A); return 0;
    case D3DFMT_A8B8G8R8: case D3DFMT_X8B8G8R8:
        dst[0]=(uint8_t)R; dst[1]=(uint8_t)G; dst[2]=(uint8_t)B; dst[3]=(uint8_t)(fmt==D3DFMT_X8B8G8R8?255:A); return 0;
    case D3DFMT_R5G6B5: {
        uint16_t v = (uint16_t)(((R>>3)<<11)|((G>>2)<<5)|(B>>3));
        dst[0]=(uint8_t)(v&0xff); dst[1]=(uint8_t)(v>>8); return 0;
    }
    case D3DFMT_A1R5G5B5: case D3DFMT_X1R5G5B5: {
        uint16_t v = (uint16_t)(((fmt==D3DFMT_A1R5G5B5 && A>=128)?0x8000:0)|((R>>3)<<10)|((G>>3)<<5)|(B>>3));
        if(fmt==D3DFMT_X1R5G5B5) v|=0x8000;
        dst[0]=(uint8_t)(v&0xff); dst[1]=(uint8_t)(v>>8); return 0;
    }
    case D3DFMT_A4R4G4B4: case D3DFMT_X4R4G4B4: {
        uint16_t v = (uint16_t)(((fmt==D3DFMT_X4R4G4B4?0xF:(A>>4))<<12)|((R>>4)<<8)|((G>>4)<<4)|(B>>4));
        dst[0]=(uint8_t)(v&0xff); dst[1]=(uint8_t)(v>>8); return 0;
    }
    case D3DFMT_A8:
        dst[0]=(uint8_t)A; return 0;
    case D3DFMT_L8:
        dst[0]=(uint8_t)((R*30+G*59+B*11)/100); return 0;
    case D3DFMT_A8L8:
        dst[0]=(uint8_t)((R*30+G*59+B*11)/100); dst[1]=(uint8_t)A; return 0;
    default:
        return -1;
    }
}

int d3dx9_fill_texture(uint32_t tex, uint32_t func, uint32_t data)
{
    if (!tex || !func) return D3DERR_INVALIDCALL;
    /* GetLevelCount() is 1 arg stdcall */
    uint32_t levels = hle_call_guest(hle_resolve("IDirect3DTexture9::GetLevelCount"), 1, (uint32_t[]){tex});
    if (!levels) levels = 1;

    void *outv = hle_alloc(16); /* D3DXVECTOR4 */
    void *coord = hle_alloc(8); /* D3DXVECTOR2 */
    void *tsize = hle_alloc(8); /* D3DXVECTOR2 */
    void *desc_mem = hle_alloc(sizeof(D3DSURFACE_DESC));
    void *lr_mem = hle_alloc(sizeof(D3DLOCKED_RECT));
    if (!outv || !coord || !tsize || !desc_mem || !lr_mem) {
        if (outv) hle_free(outv); if (coord) hle_free(coord); if (tsize) hle_free(tsize);
        if (desc_mem) hle_free(desc_mem); if (lr_mem) hle_free(lr_mem);
        return D3DERR_OUTOFVIDEOMEMORY;
    }
    uint32_t outv_va=hle_va(outv), coord_va=hle_va(coord), tsize_va=hle_va(tsize);
    uint32_t desc_va=hle_va(desc_mem), lr_va=hle_va(lr_mem);

    uint32_t hr = D3D_OK;
    for (uint32_t level=0; level<levels; level++) {
        /* GetLevelDesc(this, level, pDesc) */
        hr = hle_call_guest(hle_resolve("IDirect3DTexture9::GetLevelDesc"), 3,
                            (uint32_t[]){tex, level, desc_va});
        if (hr) goto fail;
        D3DSURFACE_DESC desc; memcpy(&desc, desc_mem, sizeof(desc));
        uint32_t w = desc.Width ? desc.Width : 1, h = desc.Height ? desc.Height : 1;
        uint32_t fmt = desc.Format;
        uint32_t bpp = d3d9_format_bytes_per_pixel(fmt);
        if (!bpp) { fprintf(stderr,"[d3dx9_tex] FillTexture: unsupported format %u\n",fmt); hr=D3DERR_NOTAVAILABLE; goto fail; }

        float ts[2] = { 1.0f/(float)w, 1.0f/(float)h };
        memcpy(tsize, ts, 8);

        /* LockRect(this, level, pLockedRect, pRect, Flags) */
        hr = hle_call_guest(hle_resolve("IDirect3DTexture9::LockRect"), 5,
                            (uint32_t[]){tex, level, lr_va, 0, 0});
        if (hr) goto fail;
        D3DLOCKED_RECT lr; memcpy(&lr, lr_mem, sizeof(lr));
        uint8_t *bits = (uint8_t*)hle_ptr(lr.pBits);
        for (uint32_t y=0; y<h; y++) {
            for (uint32_t x=0; x<w; x++) {
                float uv[2] = { ((float)x + 0.5f) * ts[0], ((float)y + 0.5f) * ts[1] };
                memcpy(coord, uv, 8);
                /* callback: (pOut, pTexCoord, pTexelSize, pData) stdcall 4 args */
                hle_call_guest(func, 4, (uint32_t[]){ outv_va, coord_va, tsize_va, data });
                float rgba[4]; memcpy(rgba, outv, 16);
                uint8_t *dst = bits + (size_t)y * (uint32_t)lr.Pitch + (size_t)x * bpp;
                if (fill_write_pixel(dst, fmt, rgba) != 0) {
                    hle_call_guest(hle_resolve("IDirect3DTexture9::UnlockRect"), 2, (uint32_t[]){tex, level});
                    fprintf(stderr,"[d3dx9_tex] FillTexture: unsupported format %u\n",fmt);
                    hr = D3DERR_NOTAVAILABLE; goto fail;
                }
            }
        }
        hle_call_guest(hle_resolve("IDirect3DTexture9::UnlockRect"), 2, (uint32_t[]){tex, level});
    }
    hle_free(outv); hle_free(coord); hle_free(tsize); hle_free(desc_mem); hle_free(lr_mem);
    return D3D_OK;
fail:
    hle_free(outv); hle_free(coord); hle_free(tsize); hle_free(desc_mem); hle_free(lr_mem);
    return hr;
}

/* ------------------------------------------------------- ComputeNormalMap */

static int read_texel_rgba(const uint8_t *p, uint32_t fmt, float rgba[4])
{
    uint32_t r=0,g=0,b=0,a=255;
    switch(fmt){
    case D3DFMT_A8R8G8B8: case D3DFMT_X8R8G8B8: b=p[0];g=p[1];r=p[2];a=(fmt==D3DFMT_X8R8G8B8)?255:p[3]; break;
    case D3DFMT_A8B8G8R8: case D3DFMT_X8B8G8R8: r=p[0];g=p[1];b=p[2];a=(fmt==D3DFMT_X8B8G8R8)?255:p[3]; break;
    case D3DFMT_R5G6B5: { uint16_t v=(uint16_t)(p[0]|(p[1]<<8)); r=((v>>11)&0x1F)*255/31; g=((v>>5)&0x3F)*255/63; b=(v&0x1F)*255/31; break; }
    case D3DFMT_A1R5G5B5: case D3DFMT_X1R5G5B5: { uint16_t v=(uint16_t)(p[0]|(p[1]<<8)); a=(v&0x8000)?255:0; r=((v>>10)&0x1F)*255/31; g=((v>>5)&0x1F)*255/31; b=(v&0x1F)*255/31; if(fmt==D3DFMT_X1R5G5B5) a=255; break; }
    case D3DFMT_A4R4G4B4: case D3DFMT_X4R4G4B4: { uint16_t v=(uint16_t)(p[0]|(p[1]<<8)); a=((v>>12)&0xF)*17; r=((v>>8)&0xF)*17; g=((v>>4)&0xF)*17; b=(v&0xF)*17; if(fmt==D3DFMT_X4R4G4B4) a=255; break; }
    case D3DFMT_L8: r=g=b=p[0]; break;
    case D3DFMT_A8L8: r=g=b=p[0]; a=p[1]; break;
    case D3DFMT_A8: a=p[0]; r=g=b=255; break;
    default: return -1;
    }
    rgba[0]=r/255.0f; rgba[1]=g/255.0f; rgba[2]=b/255.0f; rgba[3]=a/255.0f; return 0;
}

static float channel_value(const float rgba[4], uint32_t channel)
{
    /* D3DX_CHANNEL_RED=1, GREEN=2, BLUE=4, ALPHA=8, LUMINANCE=16 */
    if (channel == 1) return rgba[0];
    if (channel == 2) return rgba[1];
    if (channel == 4) return rgba[2];
    if (channel == 8) return rgba[3];
    /* LUMINANCE or default */
    return rgba[0]*0.2125f + rgba[1]*0.7154f + rgba[2]*0.0721f;
}

int d3dx9_compute_normal_map(uint32_t tex, uint32_t src_tex, uint32_t flags,
                              uint32_t channel, float amplitude)
{
    if (!tex || !src_tex) return D3DERR_INVALIDCALL;
    (void)flags;
    void *desc_mem = hle_alloc(sizeof(D3DSURFACE_DESC));
    void *lr_mem = hle_alloc(sizeof(D3DLOCKED_RECT));
    void *desc2_mem = hle_alloc(sizeof(D3DSURFACE_DESC));
    void *lr2_mem = hle_alloc(sizeof(D3DLOCKED_RECT));
    if(!desc_mem||!lr_mem||!desc2_mem||!lr2_mem){ 
        if(desc_mem) hle_free(desc_mem); if(lr_mem) hle_free(lr_mem);
        if(desc2_mem) hle_free(desc2_mem); if(lr2_mem) hle_free(lr2_mem);
        return D3DERR_OUTOFVIDEOMEMORY; }
    uint32_t hr;
    hr = hle_call_guest(hle_resolve("IDirect3DTexture9::GetLevelDesc"), 3, (uint32_t[]){src_tex,0,hle_va(desc_mem)});
    if (hr) goto out;
    hr = hle_call_guest(hle_resolve("IDirect3DTexture9::GetLevelDesc"), 3, (uint32_t[]){tex,0,hle_va(desc2_mem)});
    if (hr) goto out;
    D3DSURFACE_DESC sd, dd; memcpy(&sd, desc_mem, sizeof(sd)); memcpy(&dd, desc2_mem, sizeof(dd));
    if (sd.Width!=dd.Width || sd.Height!=dd.Height) { hr=D3DERR_INVALIDCALL; goto out; }
    uint32_t w=sd.Width, h=sd.Height;
    uint32_t sbpp=d3d9_format_bytes_per_pixel(sd.Format), dbpp=d3d9_format_bytes_per_pixel(dd.Format);
    if(!sbpp||!dbpp){ fprintf(stderr,"[d3dx9_tex] ComputeNormalMap: unsupported format\n"); hr=D3DERR_NOTAVAILABLE; goto out; }
    hr = hle_call_guest(hle_resolve("IDirect3DTexture9::LockRect"), 5, (uint32_t[]){src_tex,0,hle_va(lr_mem),0,0x10/*D3DLOCK_READONLY*/});
    if (hr) goto out;
    hr = hle_call_guest(hle_resolve("IDirect3DTexture9::LockRect"), 5, (uint32_t[]){tex,0,hle_va(lr2_mem),0,0});
    if (hr) { hle_call_guest(hle_resolve("IDirect3DTexture9::UnlockRect"),2,(uint32_t[]){src_tex,0}); goto out; }
    D3DLOCKED_RECT slr, dlr; memcpy(&slr, lr_mem, sizeof(slr)); memcpy(&dlr, lr2_mem, sizeof(dlr));
    uint8_t *src=(uint8_t*)hle_ptr(slr.pBits), *dst=(uint8_t*)hle_ptr(dlr.pBits);
    for(uint32_t y=0;y<h;y++){
        for(uint32_t x=0;x<w;x++){
            uint32_t xm=(x==0)?0:x-1, xp=(x+1>=w)?w-1:x+1;
            uint32_t ym=(y==0)?0:y-1, yp=(y+1>=h)?h-1:y+1;
            float rgba[4];
            read_texel_rgba(src + y*(uint32_t)slr.Pitch + xm*sbpp, sd.Format, rgba); float hl=channel_value(rgba,channel);
            read_texel_rgba(src + y*(uint32_t)slr.Pitch + xp*sbpp, sd.Format, rgba); float hrgt=channel_value(rgba,channel);
            read_texel_rgba(src + ym*(uint32_t)slr.Pitch + x*sbpp, sd.Format, rgba); float hu=channel_value(rgba,channel);
            read_texel_rgba(src + yp*(uint32_t)slr.Pitch + x*sbpp, sd.Format, rgba); float hd=channel_value(rgba,channel);
            float nx = (hl - hrgt) * amplitude;
            float ny = (hu - hd) * amplitude;
            float nz = 1.0f;
            float len = sqrtf(nx*nx+ny*ny+nz*nz);
            if(len>0){ nx/=len; ny/=len; nz/=len; }
            float out[4] = { nx*0.5f+0.5f, ny*0.5f+0.5f, nz*0.5f+0.5f, 1.0f };
            if(fill_write_pixel(dst + y*(uint32_t)dlr.Pitch + x*dbpp, dd.Format, out)!=0){
                hle_call_guest(hle_resolve("IDirect3DTexture9::UnlockRect"),2,(uint32_t[]){tex,0});
                hle_call_guest(hle_resolve("IDirect3DTexture9::UnlockRect"),2,(uint32_t[]){src_tex,0});
                hr=D3DERR_NOTAVAILABLE; goto out;
            }
        }
    }
    hle_call_guest(hle_resolve("IDirect3DTexture9::UnlockRect"),2,(uint32_t[]){tex,0});
    hle_call_guest(hle_resolve("IDirect3DTexture9::UnlockRect"),2,(uint32_t[]){src_tex,0});
    hr = D3D_OK;
out:
    hle_free(desc_mem); hle_free(lr_mem); hle_free(desc2_mem); hle_free(lr2_mem);
    return hr;
}

/* --------------------------------------------------- SaveTextureToFileA */

static int tex_dds_pixfmt(uint32_t fmt, uint8_t pf[32])
{
    uint32_t v[8] = { 32, 0, 0, 0, 0, 0, 0, 0 };
    switch (fmt) {
    case D3DFMT_A8R8G8B8: v[1]=0x41; v[3]=32; v[4]=0x00FF0000u; v[5]=0x0000FF00u; v[6]=0x000000FFu; v[7]=0xFF000000u; break;
    case D3DFMT_X8R8G8B8: v[1]=0x40; v[3]=32; v[4]=0x00FF0000u; v[5]=0x0000FF00u; v[6]=0x000000FFu; break;
    case D3DFMT_R5G6B5:   v[1]=0x40; v[3]=16; v[4]=0x0000F800u; v[5]=0x000007E0u; v[6]=0x0000001Fu; break;
    case D3DFMT_X1R5G5B5: v[1]=0x40; v[3]=16; v[4]=0x00007C00u; v[5]=0x000003E0u; v[6]=0x0000001Fu; break;
    case D3DFMT_A1R5G5B5: v[1]=0x41; v[3]=16; v[4]=0x00007C00u; v[5]=0x000003E0u; v[6]=0x0000001Fu; v[7]=0x00008000u; break;
    case D3DFMT_A4R4G4B4: v[1]=0x41; v[3]=16; v[4]=0x00000F00u; v[5]=0x000000F0u; v[6]=0x0000000Fu; v[7]=0x0000F000u; break;
    case D3DFMT_X4R4G4B4: v[1]=0x40; v[3]=16; v[4]=0x00000F00u; v[5]=0x000000F0u; v[6]=0x0000000Fu; break;
    case D3DFMT_A8:       v[1]=0x02; v[3]=8;  v[7]=0x000000FFu; break;
    case D3DFMT_L8:       v[1]=0x20000; v[3]=8; v[4]=0x000000FFu; break;
    case D3DFMT_A8L8:     v[1]=0x20001; v[3]=16; v[4]=0x000000FFu; v[7]=0x0000FF00u; break;
    case D3DFMT_DXT1: case D3DFMT_DXT3: case D3DFMT_DXT5:
        v[1]=0x04; v[2]=fmt; break;
    default: return -1;
    }
    memcpy(pf, v, 32);
    return 0;
}

int d3dx9_save_texture_to_file_a(const char *pDestFile, uint32_t DestFormat,
                                 uint32_t pSrcTexture, const void *pSrcPalette)
{
    if (!pDestFile || !pSrcTexture) return D3DERR_INVALIDCALL;
    if (pSrcPalette) { fprintf(stderr, "[d3dx9] SaveTextureToFileA: palette not supported\n"); return D3DERR_NOTAVAILABLE; }
    if (DestFormat != D3DXIFF_BMP && DestFormat != D3DXIFF_DDS) {
        fprintf(stderr, "[d3dx9] SaveTextureToFileA: unsupported format %u\n", DestFormat);
        return D3DERR_INVALIDCALL;
    }
    /* determine texture type via GetLevelDesc; only 2D textures supported here */
    uint32_t levels = hle_call_guest(hle_resolve("IDirect3DTexture9::GetLevelCount"), 1, (uint32_t[]){pSrcTexture});
    if (!levels) levels = 1;
    void *desc_mem = hle_alloc(sizeof(D3DSURFACE_DESC));
    void *lr_mem = hle_alloc(sizeof(D3DLOCKED_RECT));
    if (!desc_mem || !lr_mem) { if(desc_mem) hle_free(desc_mem); if(lr_mem) hle_free(lr_mem); return D3DERR_OUTOFVIDEOMEMORY; }
    uint32_t desc_va = hle_va(desc_mem), lr_va = hle_va(lr_mem);
    uint32_t hr = hle_call_guest(hle_resolve("IDirect3DTexture9::GetLevelDesc"), 3, (uint32_t[]){pSrcTexture, 0, desc_va});
    if (hr) { hle_free(desc_mem); hle_free(lr_mem); return D3DERR_INVALIDCALL; }
    D3DSURFACE_DESC desc; memcpy(&desc, desc_mem, sizeof(desc));

    if (DestFormat == D3DXIFF_BMP) {
        if (levels < 1) { hle_free(desc_mem); hle_free(lr_mem); return D3DERR_INVALIDCALL; }
        hr = hle_call_guest(hle_resolve("IDirect3DTexture9::LockRect"), 5, (uint32_t[]){pSrcTexture,0,lr_va,0,0x10u});
        if (hr) { hle_free(desc_mem); hle_free(lr_mem); return hr; }
        D3DLOCKED_RECT lr; memcpy(&lr, lr_mem, sizeof(lr));
        uint32_t w = desc.Width, h = desc.Height;
        uint32_t rowsz = (w * 3u + 3u) & ~3u;
        uint8_t *row = (uint8_t *)malloc((size_t)w * 4u ? (size_t)w * 4u : 4);
        /* zeroed so the BMP row padding bytes are deterministic */
        uint8_t *out = (uint8_t *)calloc(1, (size_t)rowsz * h ? (size_t)rowsz * h : 1);
        int bad = (!row || !out);
        if (!bad) {
            for (uint32_t y = 0; y < h && !bad; y++) {
                const uint8_t *srow = (const uint8_t *)hle_ptr(lr.pBits) + (size_t)y * (uint32_t)lr.Pitch;
                if (d3d9_format_to_bgra8(desc.Format, srow, (uint32_t)lr.Pitch, w, 1, row, w * 4u) != 0) { bad = 1; break; }
                uint8_t *o = out + (size_t)(h - 1u - y) * rowsz;
                for (uint32_t x = 0; x < w; x++) { o[x*3]=row[x*4]; o[x*3+1]=row[x*4+1]; o[x*3+2]=row[x*4+2]; }
            }
        }
        hle_call_guest(hle_resolve("IDirect3DTexture9::UnlockRect"), 2, (uint32_t[]){pSrcTexture,0});
        if (bad) { free(row); free(out); hle_free(desc_mem); hle_free(lr_mem); return D3DERR_NOTAVAILABLE; }
        FILE *f = fopen(pDestFile, "wb");
        if (!f) {
            fprintf(stderr, "[d3dx9] SaveTextureToFileA: cannot write '%s'\n", pDestFile);
            free(row); free(out); hle_free(desc_mem); hle_free(lr_mem); return D3DXERR_INVALIDDATA;
        }
        uint32_t imgsz = rowsz * h, fsize = 54u + imgsz;
        uint8_t hdr[54]; memset(hdr,0,sizeof hdr);
        hdr[0]='B'; hdr[1]='M';
        hdr[2]=(uint8_t)fsize; hdr[3]=(uint8_t)(fsize>>8); hdr[4]=(uint8_t)(fsize>>16); hdr[5]=(uint8_t)(fsize>>24);
        hdr[10]=54; hdr[14]=40;
        memcpy(hdr+18,&w,4); memcpy(hdr+22,&h,4);
        uint16_t pl=1,bc=24; memcpy(hdr+26,&pl,2); memcpy(hdr+28,&bc,2); memcpy(hdr+34,&imgsz,4);
        int ok = fwrite(hdr,1,sizeof hdr,f)==sizeof hdr && fwrite(out,1,imgsz,f)==imgsz;
        fclose(f); free(row); free(out); hle_free(desc_mem); hle_free(lr_mem);
        if (!ok) fprintf(stderr, "[d3dx9] SaveTextureToFileA: BMP write failed\n");
        return ok ? D3D_OK : D3DXERR_INVALIDDATA;
    }

    /* DDS: write all mip levels */
    uint8_t pf[32];
    if (tex_dds_pixfmt(desc.Format, pf) != 0) {
        fprintf(stderr, "[d3dx9] SaveTextureToFileA: DDS cannot store format 0x%08x\n", desc.Format);
        hle_free(desc_mem); hle_free(lr_mem); return D3DERR_NOTAVAILABLE;
    }
    FILE *f = fopen(pDestFile, "wb");
    if (!f) {
        fprintf(stderr, "[d3dx9] SaveTextureToFileA: cannot write '%s'\n", pDestFile);
        hle_free(desc_mem); hle_free(lr_mem); return D3DXERR_INVALIDDATA;
    }
    uint8_t hdr[128]; memset(hdr,0,sizeof hdr);
    hdr[0]='D'; hdr[1]='D'; hdr[2]='S'; hdr[3]=' ';
    put32(hdr+4,124);
    uint32_t flags = 0x1u|0x2u|0x4u|0x1000u;
    if (levels > 1) flags |= 0x20000u;
    put32(hdr+8,flags);
    put32(hdr+12,desc.Height); put32(hdr+16,desc.Width);
    uint32_t linsz = d3d9_format_is_block_compressed(desc.Format) ? d3d9_format_level_size(desc.Format, desc.Width, desc.Height)
                                                           : d3d9_format_pitch(desc.Format, desc.Width);
    put32(hdr+20, linsz);
    put32(hdr+28, levels);
    memcpy(hdr+76, pf, 32);
    uint32_t caps = 0x1000u; if (levels > 1) caps |= 0x400008u;
    put32(hdr+108, caps);
    int ok = fwrite(hdr,1,128,f)==128;
    for (uint32_t i = 0; ok && i < levels; i++) {
        hr = hle_call_guest(hle_resolve("IDirect3DTexture9::GetLevelDesc"), 3, (uint32_t[]){pSrcTexture,i,desc_va});
        if (hr) { ok = 0; break; }
        D3DSURFACE_DESC ld; memcpy(&ld, desc_mem, sizeof(ld));
        hr = hle_call_guest(hle_resolve("IDirect3DTexture9::LockRect"), 5, (uint32_t[]){pSrcTexture,i,lr_va,0,0x10u});
        if (hr) { ok = 0; break; }
        D3DLOCKED_RECT lr; memcpy(&lr, lr_mem, sizeof(lr));
        if (d3d9_format_is_block_compressed(ld.Format)) {
            uint32_t sz = d3d9_format_level_size(ld.Format, ld.Width, ld.Height);
            ok = fwrite(hle_ptr(lr.pBits), 1, sz, f) == sz;
        } else {
            uint32_t rowBytes = d3d9_format_pitch(ld.Format, ld.Width);
            for (uint32_t y = 0; ok && y < ld.Height; y++)
                ok = fwrite((const uint8_t *)hle_ptr(lr.pBits) + (size_t)y * (uint32_t)lr.Pitch, 1, rowBytes, f) == rowBytes;
        }
        hle_call_guest(hle_resolve("IDirect3DTexture9::UnlockRect"), 2, (uint32_t[]){pSrcTexture,i});
    }
    fclose(f);
    hle_free(desc_mem); hle_free(lr_mem);
    if (!ok) fprintf(stderr, "[d3dx9] SaveTextureToFileA: DDS write failed\n");
    return ok ? D3D_OK : D3DXERR_INVALIDDATA;
}
