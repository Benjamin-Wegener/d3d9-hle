int d3dx9_texture_create_from_file_memory(uint32_t dev, const void *pSrcData, uint32_t size,
                                          uint32_t width, uint32_t height, uint32_t mipLevels,
                                          uint32_t usage, uint32_t fmt, uint32_t pool,
                                          uint32_t *ppTex, d3dx9_texture_info *pSrcInfo)
{
    if (!dev || !pSrcData || !ppTex || !size || size > D3D9_TEX_MAX_SRC) {
        tex_log("CreateTextureFromFileInMemory: invalid arguments");
        return D3DERR_INVALIDCALL;
    }
    if (usage & ~(D3DUSAGE_RENDERTARGET | D3DUSAGE_DYNAMIC | D3DUSAGE_AUTOGENMIPMAP)) {
        tex_log("CreateTextureFromFileInMemory: unsupported usage");
        return D3DERR_INVALIDCALL;
    }
    if (pool > D3DPOOL_SYSTEMMEM) {
        tex_log("CreateTextureFromFileInMemory: invalid pool");
        return D3DERR_INVALIDCALL;
    }
    if ((width != D3DX_DEFAULT && width > D3D9_TEX_MAX_DIM) ||
        (height != D3DX_DEFAULT && height > D3D9_TEX_MAX_DIM)) {
        tex_log("CreateTextureFromFileInMemory: invalid requested size");
        return D3DERR_INVALIDCALL;
    }

    uint32_t which;
    int hr = sniff(pSrcData, size, &which);
    if (hr) { tex_log("CreateTextureFromFileInMemory: unknown image format"); return hr; }

    d3dx9_texture_info info;
    memset(&info, 0, sizeof info);
    hr = (which == D3DXIFF_DDS) ? dds_info(pSrcData, size, &info)
        : (which == D3DXIFF_TGA) ? tga_info(pSrcData, size, &info)
        : bmp_info(pSrcData, size, &info);
    if (hr) { tex_log("CreateTextureFromFileInMemory: invalid or unsupported image data"); return hr; }

    if (info.ResourceType != D3DRTYPE_TEXTURE) {
        tex_log("CreateTextureFromFileInMemory: only 2D textures supported (file is a cubemap)");
        return D3DERR_NOTAVAILABLE;
    }
    if (fmt != D3DFMT_UNKNOWN && fmt != info.Format) {
        fprintf(stderr, "[d3dx9] CreateTextureFromFileInMemory: format 0x%08x does not match file 0x%08x\n",
                fmt, info.Format);
        return D3DERR_NOTAVAILABLE;
    }

    uint32_t w = width, h = height;
    if (w == 0 || w == D3DX_DEFAULT) w = info.Width;
    if (h == 0 || h == D3DX_DEFAULT) h = info.Height;
    if (w != info.Width || h != info.Height) {
        fprintf(stderr, "[d3dx9] CreateTextureFromFileInMemory: resampling %ux%u -> %ux%u not supported\n",
                info.Width, info.Height, w, h);
        return D3DERR_NOTAVAILABLE;
    }
    if (!w || !h || w > D3D9_TEX_MAX_DIM || h > D3D9_TEX_MAX_DIM)
        return D3DERR_INVALIDCALL;

    uint32_t levels = mipLevels;
    if (levels == 0 || levels == D3DX_DEFAULT) levels = info.MipLevels;
    else if (levels > info.MipLevels) levels = info.MipLevels;
    if (levels > D3D9_TEX_MAX_LEVELS) levels = D3D9_TEX_MAX_LEVELS;
    if (!levels) levels = 1;

    if (pSrcInfo) *pSrcInfo = info;
    *ppTex = 0;

    void *outp = hle_alloc(4);
    if (!outp) return D3DERR_OUTOFVIDEOMEMORY;
    uint32_t out_va = hle_va(outp);
    uint32_t a[9] = { dev, w, h, levels, usage, info.Format, pool, out_va, 0 };
    hr = hle_call_guest(hle_resolve("IDirect3DDevice9::CreateTexture"), 9, a);
    if (hr) { hle_free(outp); return hr; }
    uint32_t tex = MEM32(out_va);
    hle_free(outp);

    if (which == D3DXIFF_DDS) {
        hr = dds_upload(tex, pSrcData, size, &info, levels);
        if (!hr) *ppTex = tex;
        return hr;
    }

    uint8_t *base = NULL;
    hr = (which == D3DXIFF_TGA) ? tga_decode(pSrcData, size, &info, &base)
        : bmp_decode(pSrcData, size, &info, &base);
    if (hr) return hr;
    hr = upload_levels_decoded(tex, base, w, h, levels);
    free(base);
    if (hr) return hr;
    *ppTex = tex;
    return 0;
}


